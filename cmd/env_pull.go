// dotenvQuote renders a value so every dotenv dialect (dotenv, @next/env with
// dotenv-expand, godotenv, python-dotenv, docker compose, a shell `source`)
// reads it back literally. Single quotes are the only form none of them
// expand or unescape, so they are the default; a value holding a single
// quote or a line break falls back to double quotes with the escapes those
// dialects agree on.
func dotenvQuote(v string) string {
	if !strings.ContainsAny(v, "'\n\r") {
		return "'" + v + "'"
	}
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\n`, "\r", `\r`)
	return `"` + r.Replace(v) + `"`
}

// renderDotenv writes the header then KEY=value lines in key order, so two
// pulls of the same site diff cleanly.
func renderDotenv(header string, env map[string]string) string {
	var b strings.Builder
	b.WriteString(header)
	if !strings.HasSuffix(header, "\n") {
		b.WriteString("\n")
	}
	for _, k := range sortedKeys(env) {
		b.WriteString(k)
		b.WriteString("=")
		b.WriteString(dotenvQuote(env[k]))
		b.WriteString("\n")
	}
	return b.String()
}

// pullHeader says which set the file holds: the local view, or (--all, or a
// platform older than the view) exactly what the pod receives.
func pullHeader(projectName, siteSlug string, local bool) string {
	what := "Effective variables: exactly what the deployed app receives."
	if local {
		what = "Variables for local development: the site's own plus the ones the platform derives."
	}
	return fmt.Sprintf("# Generated by `ghayma env pull` for %s/%s on %s\n# %s Contains secrets — keep this file out of git.\n",
		projectName, siteSlug, time.Now().UTC().Format(time.RFC3339), what)
}

// inClusterSuffix marks an address only a pod of the platform resolves.
const inClusterSuffix = ".svc.cluster.local"

// localViewNotes are the lines that say how the file differs from the pod's
// set, and which addresses in it still cannot be reached from here, so nothing
// is left out, changed or broken silently. Names only, never values.
func localViewNotes(e *api.EffectiveEnv) []string {
	if e == nil || e.View != api.ViewLocal {
		return nil
	}
	var notes []string
	var left []string
	if n := e.Omitted.LegacyAliases; n > 0 {
		left = append(left, fmt.Sprintf("%d legacy %s", n, oneOrMany(n, "alias", "aliases")))
	}
	if n := e.Omitted.PerAppDuplicates; n > 0 {
		left = append(left, fmt.Sprintf("%d per-app %s of the names above", n, oneOrMany(n, "duplicate", "duplicates")))
	}
	if len(left) > 0 {
		notes = append(notes, "Left out: "+strings.Join(left, ", ")+" — `ghayma env pull --all` writes everything the deployed app receives.")
	}
	if len(e.Rewritten) > 0 {
		verb := oneOrMany(len(e.Rewritten), "holds", "hold")
		notes = append(notes, strings.Join(e.Rewritten, ", ")+" "+verb+" the public address here; the deployed app gets the in-cluster one, which this machine cannot reach.")
	}
	var inside []string
	for _, k := range sortedKeys(e.Env) {
		if strings.Contains(e.Env[k], inClusterSuffix) {
			inside = append(inside, k)
		}
	}
	if len(inside) > 0 {
		verb := oneOrMany(len(inside), "points", "point")
		notes = append(notes, strings.Join(inside, ", ")+" "+verb+" inside the platform and will not resolve on this machine; for a database, `ghayma connect --local` opens a way in.")
	}
	return notes
}

func oneOrMany(n int, one, many string) string {
	if n == 1 {
		return one
	}
	return many
}

// envPullRefusal decides whether writing the file is safe. A tracked file is
// never written — the next commit would publish every secret. Inside a
// repository an unignored file is refused too unless --force, since
// `git add .` would stage it.
func envPullRefusal(tracked, ignored, inRepo, force bool, name string) error {
	if tracked {
		return fmt.Errorf("%s is tracked by git — the secrets would land in your next commit. Untrack it (git rm --cached %s), add it to .gitignore, then re-run", name, name)
	}
	if inRepo && !ignored && !force {
		return fmt.Errorf("%s is not git-ignored — add it (echo '%s' >> .gitignore) or pass --force to write it anyway", name, name)
	}
	return nil
}

// gitFileState asks git whether the path is tracked and whether it is ignored.
// No git on PATH, or no repository, reads as "not in a repository": nothing
// can be tracked there. Exit codes: ls-files --error-unmatch is 0 iff tracked;
// check-ignore is 0 iff ignored, 1 iff not, 128 outside a repository.
func gitFileState(path string) (tracked, ignored, inRepo bool) {
	dir, name := filepath.Split(path)
	if dir == "" {
		dir = "."
	}
	run := func(args ...string) (int, bool) {
		cmd := exec.Command("git", append([]string{"-C", dir}, args...)...)
		cmd.Stdout, cmd.Stderr = nil, nil
		if err := cmd.Run(); err != nil {
			if exit, ok := err.(*exec.ExitError); ok {
				return exit.ExitCode(), true
			}
			return -1, false // git missing or unrunnable
		}
		return 0, true
	}
	code, ran := run("ls-files", "--error-unmatch", "--", name)
	if !ran || code == 128 {
		return false, false, false
	}
	tracked = code == 0
	code, ran = run("check-ignore", "-q", "--", name)
	if !ran || code == 128 {
		return tracked, false, tracked
	}
	return tracked, code == 0, true
}

// sourceBadge annotates one pulled key with where its value came from. What is
// written to the file does not change — `env pull` has always written the
// EFFECTIVE environment — but a dev site that inherits and derives now has
// three kinds of row in it, and "which of these is production's?" is the
// question the file otherwise cannot answer. Unknown or absent (an older
// platform sends no provenance) prints nothing.
func sourceBadge(source string) string {
	switch source {
	case api.SourceInherited:
		return "  (inherited)"
	case api.SourceDerived:
		return "  (derived)"
	case api.SourceOwn:
		return "  (own)"
	}
	return ""
}

// provenanceSummary is the one-line count per source, or "" when the platform
// sent no provenance at all.
func provenanceSummary(env, sources map[string]string) string {
	if len(sources) == 0 {
		return ""
	}
	counts := map[string]int{}
	for k := range env {
		counts[sources[k]]++
	}
	var parts []string
	for _, source := range []string{api.SourceOwn, api.SourceInherited, api.SourceDerived} {
		if counts[source] > 0 {
			parts = append(parts, fmt.Sprintf("%d %s", counts[source], source))
		}
	}
	if len(parts) == 0 {
		return ""
	}
	return "   " + strings.Join(parts, " · ") + " — derived values (database URLs, bucket keys, the managed key) are this site's own; inherited ones come from the default site."
}

func runEnvPull(cmd *cobra.Command, args []string) {
	cfg := config.Load()
	if !cfg.LoggedIn() {
		failf("Please login first: ghayma login")
		return
	}
	client := api.NewClient(cfg)
	target, err := resolveConnectionTarget(client, envSite, "pull env vars for")
	if err != nil {
		reportSiteError(err)
		exitFn(1)
		return
	}

	out := localEnvPath(envPullOut, target.AppDir)
	tracked, ignored, inRepo := gitFileState(out)
	if err := envPullRefusal(tracked, ignored, inRepo, envPullForce, filepath.Base(out)); err != nil {
		failf("%v", err)
		return
	}

	fetch := client.LocalSiteEnv
	if envPullAll {
		fetch = client.EffectiveSiteEnv
	}
	effective, err := fetch(target.ProjectID, target.Site.ID)
	if err != nil {
		switch {
		case strings.Contains(err.Error(), "insufficient role"):
			failf("The project admin role is needed to pull effective variables (they include service credentials) — ask the project owner")
			return
		case strings.Contains(err.Error(), "404 page not found"):
			// A bare 404 is the route itself missing: a CLI released ahead of the
			// platform update, not a site or project that is not there.
			failf("This platform does not serve effective variables yet — the update that adds them is not deployed. Until then: ghayma env list")
			return
		}
		failf("Failed to pull env vars: %v", err)
		return
	}

	env, sources := effective.Env, effective.Sources
	data := renderDotenv(pullHeader(target.ProjectName, target.Site.Slug, effective.View == api.ViewLocal), env)
	if err := os.WriteFile(out, []byte(data), 0o600); err != nil {
		failf("Failed to write %s: %v", out, err)
		return
	}

	fmt.Printf("✅ Wrote %d variables for '%s' to %s\n", len(env), target.Site.Slug, displayPath(out))
	for _, k := range sortedKeys(env) {
		fmt.Printf("   %s%s\n", k, sourceBadge(sources[k]))
	}
	if line := provenanceSummary(env, sources); line != "" {
		fmt.Println("\n" + line)
	}
	for _, note := range localViewNotes(effective) {
		fmt.Println("   " + note)
	}
	fmt.Println("\n   Contains secrets — keep it out of git. Values are never printed here; open the file.")
}
